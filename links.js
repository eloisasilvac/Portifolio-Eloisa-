function destinoSeguro(valor, contato = false) {
  try {
    const url = new URL(valor);
    return ["https:", ...(contato ? ["mailto:"] : [])].includes(url.protocol) ? url.href : "";
  } catch { return ""; }
}

const catalogo = document.getElementById("shopping-links");
const navegacao = document.getElementById("shopping-categories");
if (catalogo) {
  linksEloisa.categorias.forEach(categoria => {
    const section = document.createElement("section");
    section.className = "product-category";
    section.id = "produtos-" + categoria.id;
    const heading = document.createElement("h3");
    heading.id = section.id + "-title";
    heading.textContent = categoria.titulo;
    section.setAttribute("aria-labelledby", heading.id);
    const description = document.createElement("p");
    description.className = "product-category__description";
    description.textContent = categoria.descricao;
    const grid = document.createElement("div");
    grid.className = "product-grid";
    linksEloisa.compras.filter(item => item.categoria === categoria.id).forEach(item => {
      const card = document.createElement("a");
      card.className = "product-card";
      card.href = destinoSeguro(item.url);
      card.target = "_blank";
      card.rel = "sponsored noopener noreferrer";
      const photo = document.createElement("img");
      photo.className = "product-card__image";
      photo.src = destinoSeguro(item.imagem);
      // O nome completo está no título do mesmo link.
      photo.alt = "";
      photo.loading = "lazy";
      photo.decoding = "async";
      photo.width = 420; photo.height = 420;
      photo.addEventListener("error", () => {
        photo.hidden = true;
        card.classList.add("product-card--no-image");
      });
      const title = document.createElement("h4");
      title.textContent = item.titulo;
      const action = document.createElement("span");
      action.className = "product-card__action";
      action.textContent = "Ver produto na Ybera ↗";
      card.append(photo, title, action);
      grid.append(card);
    });
    section.append(heading, description, grid);
    catalogo.append(section);
    if (navegacao) {
      const link = document.createElement("a");
      link.href = "#" + section.id;
      link.textContent = categoria.titulo;
      navegacao.append(link);
    }
  });
}
